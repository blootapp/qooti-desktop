export function initI18n(savedLang) {
  if (savedLang && strings[savedLang]) lang = savedLang
  applyToDOM()
}

export function setLang(newLang) {
  if (!strings[newLang]) return
  lang = newLang
  applyToDOM()
  // Notify modules that render text imperatively (t() at build time) so they
  // can re-render — data-i18n elements are handled by applyToDOM above.
  document.dispatchEvent(new CustomEvent('i18n:changed', { detail: { lang } }))
}

export function currentLang() { return lang }

export function t(key, vars = {}) {
  const str = strings[lang]?.[key] ?? strings.en?.[key] ?? key
  return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`)
}

function applyToDOM() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n
    el.textContent = t(key)
  })
  // Icon buttons: the tooltip and the name screen readers say
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const text = t(el.dataset.i18nTitle)
    el.title = text
    el.setAttribute('aria-label', text)
  })
}
